#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Photobooth AI — migrate an existing checkout into the canonical /opt path.
#
# Run AFTER scripts/bootstrap_vps.sh has created /opt/photobooth.
# This script needs NO privileges.
#
# WHAT IT DOES
#   1. verifies /opt/photobooth + /srv/photobooth exist and are writable
#   2. copies the project source into /opt/photobooth (rsync, excludes
#      build artefacts, .venv, node_modules and .env)
#   3. writes /opt/photobooth/.env from the source .env so no secret is ever
#      committed or printed
#   4. re-points the runtime at the HOST /srv/photobooth tree via bind mounts
#      (compose override), replacing the named volume
#   5. prepares/verifies runtime permissions for the image's non-root user
#   6. validates the new compose config and reports the exact next commands
#
# WHAT IT DOES NOT DO
#   - it does NOT stop, start, remove or recreate any container
#   - it does NOT touch another project's container, network or volume
#   - it does NOT run docker system prune
#   - it does NOT delete the source checkout
#
# The old stack keeps running until you explicitly bring the new one up, so
# there is no downtime window and rollback is simply "keep using the old one".
#
# USAGE:
#   bash /home/mahez/photoboothai/scripts/migrate_to_opt.sh [SOURCE_DIR]
# ---------------------------------------------------------------------------
set -euo pipefail

SRC="${1:-/home/mahez/photoboothai}"
APP_DIR="/opt/photobooth"
RUNTIME_DIR="/srv/photobooth"

echo "== Photobooth AI migration =="
echo "   source : $SRC"
echo "   target : $APP_DIR"
echo

# --- 1. preflight ----------------------------------------------------------
if [[ "$(id -u)" -eq 0 ]]; then
  echo "WARN: running as root; files will be root-owned. Prefer the deploy user." >&2
fi

for dir in "$SRC" "$APP_DIR" "$RUNTIME_DIR"; do
  if [[ ! -d "$dir" ]]; then
    echo "ERROR: missing directory: $dir" >&2
    echo "       Run scripts/bootstrap_vps.sh with sudo first." >&2
    exit 1
  fi
done

for dir in "$APP_DIR" "$RUNTIME_DIR"; do
  if [[ ! -w "$dir" ]]; then
    echo "ERROR: not writable by $(id -un): $dir" >&2
    echo "       Re-run scripts/bootstrap_vps.sh (it chowns both trees)." >&2
    exit 1
  fi
done

if [[ ! -f "$SRC/docker-compose.yml" ]]; then
  echo "ERROR: $SRC/docker-compose.yml not found — wrong source directory?" >&2
  exit 1
fi

# --- 2. copy source --------------------------------------------------------
if ! command -v rsync >/dev/null 2>&1; then
  echo "ERROR: rsync is required. Install it or copy the tree manually." >&2
  exit 1
fi

# Do not delete excluded files: this protects production-only files such as
# .env, runtime overrides, and any operator-maintained deployment config.
rsync -a \
  --exclude '.git/' \
  --exclude '.venv/' \
  --exclude '__pycache__/' \
  --exclude '.pytest_cache/' \
  --exclude 'node_modules/' \
  --exclude 'dist/' \
  --exclude '.env' \
  --exclude 'runtime/' \
  "$SRC"/ "$APP_DIR"/
echo "[ok] source copied to $APP_DIR"

# --- 3. secrets: preserve production .env, never print --------------------
# The active deployment is authoritative for secrets. Only bootstrap .env
# when the target does not have one; never overwrite an existing production
# environment with a developer checkout's values.
if [[ -f "$APP_DIR/.env" ]]; then
  chmod 0600 "$APP_DIR/.env"
  echo "[ok] existing production .env preserved (contents not displayed)"
elif [[ -f "$SRC/.env" ]]; then
  install -m 0600 "$SRC/.env" "$APP_DIR/.env"
  echo "[ok] .env initialized from source (mode 0600, contents not displayed)"
else
  echo "[warn] no .env found — copy .env.example and fill in values"
fi
# --- 4. compose override: host /srv/photobooth instead of a named volume ---
# Spec section 6 wants the runtime tree to live at the host path
# /srv/photobooth/{templates,tmp,cache,backups}. The base compose file uses a
# named volume so the project can run without any privileged setup; this
# override switches to the canonical host bind mounts now that they exist.
cat > "$APP_DIR/docker-compose.override.yml" <<'YAML'
# ---------------------------------------------------------------------------
# Canonical-VPS override: use the HOST /srv/photobooth runtime tree instead of
# the `photobooth_runtime` named volume (spec section 6).
#
# Generated by scripts/migrate_to_opt.sh. Requires scripts/bootstrap_vps.sh to
# have created and chowned /srv/photobooth first.
#
# To revert to the self-contained named-volume layout, delete this file.
# ---------------------------------------------------------------------------

services:
  photobooth-api:
    volumes:
      - /srv/photobooth:/srv/photobooth
      - /opt/photobooth/templates:/opt/photobooth-seed/templates:ro

  photobooth-worker:
    volumes:
      - /srv/photobooth:/srv/photobooth
      - /opt/photobooth/templates:/opt/photobooth-seed/templates:ro
YAML
echo "[ok] docker-compose.override.yml written (host /srv/photobooth bind mounts)"

# --- 5. runtime permissions -------------------------------------------------
# A bind mount keeps host ownership. The backend image deliberately runs as
# the non-root `photobooth` user, so host-side ownership alone is insufficient.
# If the local backend image exists, use its root entrypoint only to prepare
# the five application-writable runtime directories. No application data is
# deleted and the backup directory remains host-owned.
if docker image inspect photobooth-api:local >/dev/null 2>&1; then
  container_uid="$(docker run --rm --entrypoint id photobooth-api:local -u)"
  host_gid="$(id -g)"
  if [[ ! "$container_uid" =~ ^[0-9]+$ ]] || [[ ! "$host_gid" =~ ^[0-9]+$ ]]; then
    echo "ERROR: unable to determine numeric runtime ownership" >&2
    exit 1
  fi
  docker run --rm --user 0 --entrypoint sh \
    -v "$RUNTIME_DIR:/mnt" photobooth-api:local \
    -c "set -eu
for sub in templates tmp cache uploads results; do
  mkdir -p \"/mnt/\$sub\"
  chown \"${container_uid}:${host_gid}\" \"/mnt/\$sub\"
  chmod 2775 \"/mnt/\$sub\"
done"
  echo "[ok] runtime directories writable by image UID $container_uid (host group preserved)"
else
  echo "[warn] photobooth-api:local is not built yet; verify runtime ownership after build" >&2
fi

# --- 6. validate -----------------------------------------------------------
cd "$APP_DIR"
echo
echo "== Validating compose configuration at $APP_DIR =="
if docker compose config --quiet; then
  echo "[ok] COMPOSE_CONFIG_VALID"
else
  echo "[FAIL] compose config invalid — do not start the stack" >&2
  exit 1
fi

echo
echo "== Migration prepared. Nothing was started or stopped. =="
echo
echo "The existing stack is still running and still owns:"
echo "  container names : photobooth-{api,web,worker,postgres,redis}"
echo "  network         : photobooth-net"
echo "  host ports      : 3000, 8000"
echo
echo "Because docker-compose.yml hardcodes container_name and network name, the"
echo "two checkouts CANNOT run at the same time. Choose one:"
echo
echo "  (a) Cutover (brief downtime, keeps data):"
echo "        cd $SRC      && docker compose down      # stops ONLY photobooth"
echo "        cd $APP_DIR  && docker compose up -d --build"
echo "      Postgres/Redis data survives: both use the same named volumes"
echo "      photobooth_pgdata / photobooth_redisdata."
echo
echo "  (b) Keep the current location and treat /opt/photobooth as the deploy"
echo "      target for a later release."
echo
echo "Verify after cutover:"
echo "  docker compose ps"
echo "  curl -sS http://127.0.0.1:8000/api/health"
echo "  curl -sS http://127.0.0.1:3000/api/health"
